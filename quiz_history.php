    // ---------- chart code (same design) ----------
    function extractPercentage(scoreStr){
      const parts = (scoreStr || "").split("/");
      if (parts.length === 2) {
        const val = (parseInt(parts[0], 10) / parseInt(parts[1], 10)) * 100;
        return isNaN(val) ? null : Math.round(val);
      }
      return null;
    }

    function renderChart(history) {
      const getQuizData = () => history.map((record, i) => ({
        label: `Quiz ${i + 1}`,
        value: extractPercentage(record.score),
      }));

      const getDailyData = () => {
        const dateMap = {};
        let minDate = null, maxDate = null;

        history.forEach(record => {
          const dateStr = (record.datetime || "").split(" ")[0];
          if (!dateStr) return;
          const date = new Date(dateStr);
          const score = extractPercentage(record.score);
          if (score === null) return;
          const isoDate = date.toISOString().split("T")[0];
          if (!dateMap[isoDate]) dateMap[isoDate] = [];
          dateMap[isoDate].push(score);
          if (!minDate || date < minDate) minDate = new Date(date);
          if (!maxDate || date > maxDate) maxDate = new Date(date);
        });

        const result = [];
        if (minDate && maxDate) {
          for (let d = new Date(minDate); d <= maxDate; d.setDate(d.getDate() + 1)) {
            const iso = d.toISOString().split("T")[0];
            const scores = dateMap[iso] || [];
            const avg = scores.length ? Math.round(scores.reduce((a,b)=>a+b,0) / scores.length) : 0;
            result.push({ label: iso, value: avg });
          }
        }
        return result;
      };

      function getWeeklyData() {
        const weekMap = {};
        let minDate = null, maxDate = null;

        function safeParseDate(dateStr) {
          if (!dateStr) return null;
          const match = dateStr.match(/(\d{4})[^\d]?(\d{1,2})[^\d]?(\d{1,2})/);
          if (!match) return null;
          const [, y, m, d] = match.map(Number);
          const dt = new Date(y, m - 1, d);
          return isNaN(dt) ? null : dt;
        }

        history.forEach(record => {
          const date = safeParseDate(record.datetime);
          if (!date) return;
          const score = extractPercentage(record.score);
          if (score === null) return;

        const key = getWeekKey(date);
        if (!weekMap[key]) weekMap[key] = [];
        weekMap[key].push(score);

        if (!minDate || date < minDate) minDate = new Date(date);
        if (!maxDate || date > maxDate) maxDate = new Date(date);
      });

        const weeklyData = [];
        if (minDate && maxDate) {
          let current = new Date(minDate);
          current.setDate(current.getDate() - current.getDay());
          const last = new Date(maxDate);
          last.setDate(last.getDate() - last.getDay());
          while (current <= last) {
            const key = getWeekKey(current);
            const scores = weekMap[key] || [];
            const avg = scores.length ? Math.round(scores.reduce((a,b)=>a+b,0)/scores.length) : 0;
            weeklyData.push({ label: key, value: avg });
            current.setDate(current.getDate() + 7);
          }
        }
        return weeklyData;
      }

      function getWeekKey(date) {
        const start = new Date(date);
        start.setDate(start.getDate() - start.getDay());
        const end = new Date(start);
        end.setDate(start.getDate() + 6);
        const fmt = (d) => d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
        return `${fmt(start)} - ${fmt(end)}`;
      }

